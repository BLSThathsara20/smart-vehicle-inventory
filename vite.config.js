import { defineConfig, loadEnv } from 'vite'
import react from '@vitejs/plugin-react'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))

/** Writes `public/firebase-messaging-sw.js` from VITE_FIREBASE_* so FCM background messages work. */
function writeFirebaseMessagingSw(mode) {
  return {
    name: 'write-firebase-messaging-sw',
    buildStart() {
      const env = loadEnv(mode, process.cwd(), '')
      const cfg = {
        apiKey: env.VITE_FIREBASE_API_KEY || '',
        authDomain: env.VITE_FIREBASE_AUTH_DOMAIN || '',
        projectId: env.VITE_FIREBASE_PROJECT_ID || '',
        storageBucket: env.VITE_FIREBASE_STORAGE_BUCKET || '',
        messagingSenderId: env.VITE_FIREBASE_MESSAGING_SENDER_ID || '',
        appId: env.VITE_FIREBASE_APP_ID || '',
      }
      const out = path.resolve(__dirname, 'public/firebase-messaging-sw.js')
      if (!cfg.apiKey || !cfg.projectId || !cfg.appId) {
        fs.writeFileSync(
          out,
          `// Generated by Vite — set VITE_FIREBASE_* in .env and restart dev server or rebuild.
self.addEventListener('install', (e) => self.skipWaiting());
self.addEventListener('activate', (e) => e.waitUntil(self.clients.claim()));
`
        )
        return
      }
      const sw = `/* auto-generated — do not edit; configure Firebase in .env */
importScripts('https://www.gstatic.com/firebasejs/12.11.0/firebase-app-compat.js');
importScripts('https://www.gstatic.com/firebasejs/12.11.0/firebase-messaging-compat.js');
firebase.initializeApp(${JSON.stringify(cfg)});
const messaging = firebase.messaging();
messaging.onBackgroundMessage((payload) => {
  const title = payload.notification?.title || payload.data?.title || 'Car inventory';
  const body = payload.notification?.body || payload.data?.body || '';
  const options = {
    body,
    data: payload.data || {},
  };
  return self.registration.showNotification(title, options);
});
self.addEventListener('notificationclick', (event) => {
  event.notification.close();
  const p = event.notification?.data?.path || '/app/notifications';
  const origin = self.location && self.location.origin ? self.location.origin : '';
  const url = origin + (p.startsWith('/') ? p : '/' + p);
  event.waitUntil(
    self.clients.matchAll({ type: 'window', includeUncontrolled: true }).then((clientList) => {
      for (const client of clientList) {
        if (client.url === url && 'focus' in client) return client.focus();
      }
      if (self.clients.openWindow) return self.clients.openWindow(url);
    })
  );
});
`
      fs.writeFileSync(out, sw)
    },
  }
}

// https://vite.dev/config/
export default defineConfig(({ mode }) => ({
  plugins: [react(), writeFirebaseMessagingSw(mode)],
  base: process.env.GITHUB_ACTIONS ? '/smart-vehicle-inventory/' : '/',
}))
